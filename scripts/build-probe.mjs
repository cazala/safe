// Pinned solc, Paris EVM (no PUSH0), reproducible runtime; no compiler in the app.
import solc from 'solc';
import { readFileSync, writeFileSync } from 'node:fs';
const input = {
  language: 'Solidity',
  sources: { 'AssetProbe.sol': { content: readFileSync(new URL('../contracts/AssetProbe.sol', import.meta.url), 'utf8') } },
  settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: 'paris', metadata: { bytecodeHash: 'none', appendCBOR: false }, outputSelection: { '*': { '*': ['evm.deployedBytecode.object'] } } },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
for (const e of out.errors || []) if (e.severity === 'error') throw Error(e.formattedMessage);
const source = '// Generated by npm run build:probe; do not edit. Source: contracts/AssetProbe.sol\nexport const PROBE_CODE = "0x' + out.contracts['AssetProbe.sol'].AssetProbe.evm.deployedBytecode.object + '";\n';
const file = new URL('../src/probe-code.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== source) throw Error('AssetProbe bytecode is stale; run npm run build:probe');
} else writeFileSync(file, source);
